/** 20 × 40 m field (x 40–160, y 25–85) */
const F2040: Item = ['area', 40, 25, 120, 60, 'c']

/** waypoints of a slalom through poles on a row (x0 … x1, every dx) */
const slalom = (x0: number, x1: number, dx: number, y: number, back = false): Pt[] => {
  const pts: Pt[] = []
  const n = Math.round((x1 - x0) / dx)
  for (let i = 0; i <= n; i++) {
    const x = x0 + i * dx
    pts.push([x, y + (i % 2 ? 5 : -5)])
  }
  return back ? pts.reverse() : pts
}
const poles = (x0: number, x1: number, dx: number, y: number): Item[] => {
  const out: Item[] = []
  for (let x = x0; x <= x1 + 0.1; x += dx) out.push(['pole', x, y])
  return out
}

